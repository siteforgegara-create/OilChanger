export function fallbackMessages(locale: SupportedLocale): Record<string, string> {
  return Object.fromEntries(
    translationSeeds.map((translation) => [`${translation.namespace}.${translation.key}`, translation.values[locale]]),
  );
}

function item(
  namespace: string,
  key: string,
  isTechnical: boolean,
  az: string,
  ru: string,
  en: string,
): TranslationSeedItem {
  return {
    namespace,
    key,
    isTechnical,
    values: { az, ru, en },
  };
}
